#!/usr/bin/env python3
"""Generate/check the aligned C arrays used to embed the checked-in D3D GXP."""
from pathlib import Path
import argparse
import sys

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "src/d3d/shaders"
OUTPUT = SHADERS / "d3d6_gxp_blobs.h"
BLOBS = (
    ("d3d6_v", "d3d6_v.gxp"),
    ("d3d6_f_pal", "d3d6_f_pal.gxp"),
    ("d3d6_f_rgba", "d3d6_f_rgba.gxp"),
)


def render() -> str:
    out = ["// Generated by tools/embed_d3d_gxp.py; do not edit by hand.\n"]
    for symbol, filename in BLOBS:
        data = (SHADERS / filename).read_bytes()
        if not data.startswith(b"GXP\0"):
            raise ValueError(f"{filename}: missing GXP signature")
        out.append(f"static const unsigned int size_{symbol} = {len(data)};\n")
        out.append(
            f"static const unsigned char {symbol}[] __attribute__((aligned(16))) = {{\n"
        )
        for start in range(0, len(data), 12):
            chunk = data[start : start + 12]
            out.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",\n")
        out.append("};\n\n")
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        expected = render()
    except (OSError, ValueError) as exc:
        print(f"GXP embed: {exc}", file=sys.stderr)
        return 1
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print(f"GXP embed: stale or missing {OUTPUT}", file=sys.stderr)
            return 1
        print("GXP embed: blobs match checked-in header")
        return 0
    OUTPUT.write_text(expected)
    print(f"GXP embed: wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
